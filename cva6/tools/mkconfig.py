#!/usr/bin/env python3
"""Generate a CVA6 configuration package for one harness variant.

  mkconfig.py <cva6 clone> <base.cfg> <variant.cfg> <out_dir>

Reads core/include/<BASE_TARGET>_config_pkg.sv from the clone (BASE_TARGET is
set in base.cfg), applies the field overrides of base.cfg and then of the
variant file, and writes <out_dir>/cva6_bp55_config_pkg.sv (package name
cva6_config_pkg, as every CVA6 target package). Each override must match
exactly one `Field: type'(value),` line of the cva6_cfg literal.

Variant files may only override predictor fields (PREDICTOR_FIELDS), so that
variants of one base differ only in the branch predictor. A variant line
`BP55 1` selects BP55; it is handled by cva6/cva6.sh, not by this script.
"""
import re
import sys

PREDICTOR_FIELDS = {"BPType", "BHTEntries", "BHTHist", "BTBEntries", "RASDepth", "BP55"}


def read_cfg(path):
    out = []
    for ln in open(path):
        ln = ln.split("#", 1)[0].strip()
        if not ln:
            continue
        k, v = ln.split(None, 1)
        out.append((k, v.strip()))
    return out


def main():
    clone, base, variant, outdir = sys.argv[1:5]
    base_kv = read_cfg(base)
    var_kv = read_cfg(variant)
    target = dict(base_kv).get("BASE_TARGET")
    if not target:
        sys.exit("mkconfig: base.cfg must set BASE_TARGET")
    for k, _ in var_kv:
        if k not in PREDICTOR_FIELDS:
            sys.exit(f"mkconfig: {variant}: {k} is not a predictor field {sorted(PREDICTOR_FIELDS)}")
    # "BP55 1" selects BP55 (cva6.sh adds rtl/bp55.sv and +define+BP55_PRED); it is not
    # a field of the configuration package
    var_kv = [kv for kv in var_kv if kv[0] != "BP55"]
    src = open(f"{clone}/core/include/{target}_config_pkg.sv").read()
    applied = []
    for k, v in [kv for kv in base_kv if kv[0] != "BASE_TARGET"] + var_kv:
        pat = re.compile(r"^(\s*" + re.escape(k) + r":\s*)([^,]+)(,)", re.M)
        hits = pat.findall(src)
        if len(hits) != 1:
            sys.exit(f"mkconfig: field {k} found {len(hits)} times in {target}_config_pkg.sv")
        old = hits[0][1]
        cast = re.match(r"(\w+(?:::\w+)?)'\(", old)
        if k == "BPType":
            new = f"config_pkg::{v}"
        elif cast:
            new = f"{cast.group(1)}'({v})"
        else:
            new = v
        src = pat.sub(lambda m: m.group(1) + new + m.group(3), src)
        applied.append(f"{k}: {old} -> {new}")
    hdr = (f"// Generated by cva6/tools/mkconfig.py from {target}_config_pkg.sv\n"
           + "".join(f"//   {a}\n" for a in applied))
    open(f"{outdir}/cva6_bp55_config_pkg.sv", "w").write(hdr + src)
    print("\n".join(applied))


if __name__ == "__main__":
    main()
