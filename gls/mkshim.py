#!/usr/bin/env python3
"""Generate bp55_rtl.cc for the Verilator route: a CXXRTL-compatible facade over a Verilated netlist.

usage: mkshim.py <netlist .v|.v.gz> <Verilator obj dir> <out bp55_rtl.cc>

The co-simulation harnesses (sim/cosim.cc via gls/mkharness.py, and 8ff8f15:sim/cosim.cc) #include
"bp55_rtl.cc" and use a small part of the CXXRTL API: cxxrtl_design::p_bp55 with one member per port
(p_f__pc, p_f__meta, ...) offering set<T>() / get<T>() / .data, step(), debug_info() and (with
mkharness.py) debug_eval(), and cxxrtl::debug_items with WIRE / VALUE items. This file provides exactly
that API on top of the Verilator model, so the harness source is the same as on the CXXRTL route:
  - ports: parsed from the netlist; inputs are copied into the model before eval(), outputs copied out
    after it; step() = eval() (Verilator settles the combinational logic and clock edges in one call);
  - WIRE debug items: every flop and latch state variable of the PDK cell models (udp_dff.out,
    ipicg_latchnsr.Q, made public with gls/vl/gl.vlt), so the harness's random initialisation writes
    every state bit of the netlist; the values are pushed into the model before the first eval();
  - VALUE debug items: the netlist nets named after RTL state (bim[0], tu0, ghr, ...), read back by
    debug_eval() for the harness's post-reset clear check; ghr / thr / rasp are taken from the f_ckpt
    output port bits when the netlist has no net of that name (routed netlists).
"""
import gzip
import re
import sys

net, obj, out = sys.argv[1:4]
txt = (gzip.open(net, "rt") if net.endswith(".gz") else open(net)).read()
mod = re.search(r"^\s*module\s+bp55\b(.*?)^\s*endmodule", txt, re.S | re.M).group(1)
ports = []
for m in re.finditer(r"^\s*(input|output)\s+(?:wire\s+)?(?:\[(\d+):(\d+)\]\s*)?([A-Za-z_]\w*)\s*;", mod, re.M):
    d, hi, lo, n = m.groups()
    w = int(hi) - int(lo) + 1 if hi else 1
    ports.append((d, n, w))
if not ports:
    sys.exit("mkshim: no ports found")

hdr = open("%s/Vbp55___024root.h" % obj).read()


def demangle(s):
    s = s.replace("__DOT__", ".")
    return re.sub(r"__0([0-9a-fA-F]{2})", lambda m: chr(int(m.group(1), 16)), s)


state, named = [], []
for m in re.finditer(r"::(CData|SData|IData|QData|VlWide<\d+>)/\*(\d+):(\d+)\*/\s+(bp55__DOT__\w+);", hdr):
    ty, hi, lo, mem = m.groups()
    w = int(hi) - int(lo) + 1
    name = demangle(mem[len("bp55__DOT__"):])
    if name.endswith(".I0.out") or re.search(r"\.(I0|_i0)\.(out|Q)$", name) or name.endswith(".Q"):
        state.append((name, w, mem))
    elif "." not in name:
        named.append((name, w, mem))
state = sorted(set(state))
named = sorted(set(named))
# A routed netlist may carry the GHR / THR / RAS-pointer flops only under the output port name f_ckpt
# (rtl/bp55.sv: f_ckpt = {ras_top[31:2], rasp, thr, ghr}); expose them under their RTL names, read from
# the port, when no net of that name exists.
alias = []
pnames = {n for d, n, w in ports}
for nm, lo, w in (("ghr", 0, 28), ("thr", 28, 6), ("rasp", 34, 3)):
    if "f_ckpt" in pnames and not any(n == nm or n.startswith(nm + "[") or re.match(re.escape(nm) + r"_\d", n) for n, _, _ in named):
        alias.append((nm, lo, w))

cname = lambda n: "p_" + n.replace("_", "__")
L = []
L.append("// generated by gls/mkshim.py; do not edit")
L.append('#include "Vbp55.h"\n#include "Vbp55___024root.h"\n#include "verilated.h"')
L.append("#include <cstdint>\n#include <cstdio>\n#include <cstring>\n#include <deque>\n#include <map>\n#include <string>\n#include <type_traits>\n#include <vector>")
L.append("""namespace cxxrtl {
template <size_t N> struct value {
  static constexpr size_t chunks = (N + 31) / 32;
  uint32_t data[chunks] = {};
  template <class T> void set(T v) { uint64_t x = (uint64_t)v; for (size_t i = 0; i < chunks; i++) data[i] = i < 2 ? (uint32_t)(x >> (32 * i)) : 0; if (N % 32) data[chunks - 1] &= (1u << (N % 32)) - 1; }
  template <class T> T get() const { uint64_t x = data[0]; if (chunks > 1) x |= (uint64_t)data[1] << 32; return (T)x; }
};
template <size_t N> struct wire { value<N> curr, next; };
struct debug_item {
  enum : uint32_t { INPUT = 1, OUTPUT = 2 };
  enum : uint32_t { VALUE = 0, WIRE = 1, MEMORY = 2, ALIAS = 3, OUTLINE = 4 };
  uint32_t flags = 0, type = VALUE; size_t width = 0, depth = 1; uint32_t *curr = nullptr, *next = nullptr;
};
struct debug_items { std::map<std::string, std::vector<debug_item>> table; };
}
namespace gl {
template <class T> inline void to_model(T &d, const uint32_t *s, size_t n) {
  if constexpr (std::is_integral_v<T>) { uint64_t x = s[0]; if (n > 1) x |= (uint64_t)s[1] << 32; d = (T)x; }
  else { for (size_t i = 0; i < n; i++) d[i] = s[i]; }
}
template <class T> inline void from_model(const T &s, uint32_t *d, size_t n) {
  if constexpr (std::is_integral_v<T>) { uint64_t x = (uint64_t)s; d[0] = (uint32_t)x; if (n > 1) d[1] = (uint32_t)(x >> 32); }
  else { for (size_t i = 0; i < n; i++) d[i] = s[i]; }
}
}
namespace cxxrtl_design {
struct p_bp55 {
  VerilatedContext ctx; Vbp55 *m; bool pushed = false;""")
for d, n, w in ports:
    L.append("  cxxrtl::value<%d> %s;" % (w, cname(n)))
L.append("  std::vector<std::vector<uint32_t>> st, nm, al;")
L.append("  p_bp55() : m(new Vbp55(&ctx)) {")
L.append("    st.resize(%d); nm.resize(%d); al.resize(%d);" % (len(state), len(named), len(alias)))
for i, (nm, lo, w) in enumerate(alias):
    L.append("    al[%d].assign(%d, 0);" % (i, (w + 31) // 32))
for i, (n, w, mem) in enumerate(state):
    L.append("    st[%d].assign(%d, 0);" % (i, (w + 31) // 32))
for i, (n, w, mem) in enumerate(named):
    L.append("    nm[%d].assign(%d, 0);" % (i, (w + 31) // 32))
# The cell models' async set/reset is an event control (always @(posedge clk or negedge clr_)), so a reset
# that is already low at the first eval would only act at the next clock edge of that flop; the PDK UDP
# is level-sensitive. Settling the model once with rst_n = 1 makes the harness's rst_n = 0 a falling edge,
# which gives the level-sensitive behaviour also for flops whose (gated) clock does not toggle in reset.
if any(n == "rst_n" for d, n, w in ports):
    L.append("    m->rst_n = 1; m->eval();")
L.append("    pull();\n  }\n  ~p_bp55() { m->final(); delete m; }")
L.append("  void pull() {  // model state -> debug buffers")
for i, (n, w, mem) in enumerate(state):
    L.append("    gl::from_model(m->rootp->%s, st[%d].data(), %d);" % (mem, i, (w + 31) // 32))
for i, (n, w, mem) in enumerate(named):
    L.append("    gl::from_model(m->rootp->%s, nm[%d].data(), %d);" % (mem, i, (w + 31) // 32))
for i, (nm, lo, w) in enumerate(alias):
    L.append("    for (int b = 0; b < %d; b++) { if (b %% 32 == 0) al[%d][b / 32] = 0; if ((%s.data[(%d + b) / 32] >> ((%d + b) %% 32)) & 1) al[%d][b / 32] |= 1u << (b %% 32); }"
             % (w, i, cname("f_ckpt"), lo, lo, i))
L.append("  }")
L.append("  void push() {  // debug buffers (random initial state written by the harness) -> model")
for i, (n, w, mem) in enumerate(state):
    L.append("    gl::to_model(m->rootp->%s, st[%d].data(), %d);" % (mem, i, (w + 31) // 32))
L.append("  }")
L.append("  void step() {")
L.append("    if (!pushed) {  // push the harness's random state, read it back from the model and report it")
L.append("      push(); pushed = true; size_t ones = 0;")
L.append("      pull(); for (auto &b : st) for (uint32_t w : b) ones += __builtin_popcount(w);")
L.append('      fprintf(stderr, "GLPUSH state variables=%zu ones_after_push=%zu\\n", st.size(), ones);')
L.append("    }")
for d, n, w in ports:
    if d == "input":
        L.append("    gl::to_model(m->%s, %s.data, %d);" % (n, cname(n), (w + 31) // 32))
L.append("    m->eval();")
for d, n, w in ports:
    if d == "output":
        L.append("    gl::from_model(m->%s, %s.data, %d);" % (n, cname(n), (w + 31) // 32))
L.append("  }")
L.append("  void debug_eval() { pull(); }")
L.append("  void debug_info(cxxrtl::debug_items *items, void *, std::string) {")
L.append("    cxxrtl::debug_item it;")
for i, (n, w, mem) in enumerate(state):
    L.append('    it = {}; it.type = cxxrtl::debug_item::WIRE; it.width = %d; it.curr = it.next = st[%d].data(); items->table["%s"].push_back(it);' % (w, i, n))
for i, (n, w, mem) in enumerate(named):
    L.append('    it = {}; it.type = cxxrtl::debug_item::VALUE; it.width = %d; it.curr = nm[%d].data(); items->table["%s"].push_back(it);' % (w, i, n))
for i, (nm, lo, w) in enumerate(alias):
    L.append('    it = {}; it.type = cxxrtl::debug_item::VALUE; it.width = %d; it.curr = al[%d].data(); items->table["%s"].push_back(it);  // from f_ckpt' % (w, i, nm))
L.append("  }\n};\n}")
open(out, "w").write("\n".join(L) + "\n")
sys.stderr.write("mkshim: %d ports, %d state variables (%d bits), %d named nets, port aliases: %s\n"
                 % (len(ports), len(state), sum(w for _, w, _ in state), len(named), ",".join(a[0] for a in alias) or "none"))
