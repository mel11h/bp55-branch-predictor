#!/usr/bin/env python3
"""Turn a gate-level directed testbench (gls/mktb.py output) into an SDF-annotated, timed one.

usage: sdf_tb.py <gl_tb .sv> <sdf file> <out .sv> [low high sample]   (ns, default 4.0 2.0 3.9)

The zero-delay testbench clocks with tick() = "#1 clk=1; #1 clk=0;", changes inputs right after the
falling edge and samples combinational outputs "#0.5" later. With real delays that is a 2 ns clock
and a 0.5 ns sampling window, so the timing is changed (and nothing else):
  tick()          -> "#4 clk=1; #2 clk=0;"  (rising edges at least 6.0 ns apart, the sign-off period;
                                             2 ns high so inputs change after the ~1.2 ns clock
                                             insertion delay of the flops, i.e. after their edge)
  every "#0.5"    -> "#3.9"                 (combinational outputs sampled 3.9 ns after the inputs)
(These are the defaults; the low and high phase and the sample delay can be given on the command line.)
Rising edges are exactly 6.0 ns apart where the testbench ticks back to back (reset, clear, multi-cycle
holds, the reset sequencer); where it samples outputs in between, that cycle is 9.9 ns long.
An initial block calls $sdf_annotate on the dut. The SDF must hold the wanted corner in all three
triple positions (sdf_sim.sh rewrites OpenSTA "(min::max)" as "(max:max:max)").
"""
import sys

src, sdf, out = sys.argv[1:4]
lo, hi, smp = (sys.argv[4:7] if len(sys.argv) > 6 else ("4", "2", "3.9"))
s = open(src).read()
old = "task automatic tick(); #1 clk=1; #1 clk=0; endtask"
if s.count(old) != 1:
    sys.exit("sdf_tb: tick() not found")
s = s.replace(old, "task automatic tick(); #%s clk=1; #%s clk=0; endtask" % (lo, hi))
n = s.count("#0.5")
s = s.replace("#0.5", "#" + smp)
s = s.replace("  bp55 dut(.*);\n", '  bp55 dut(.*);\n  initial $sdf_annotate("%s", dut);\n' % sdf, 1)
open(out, "w").write("// generated by gls/sdf_tb.py; do not edit\n" + s)
sys.stderr.write("sdf_tb: %d sample delays rescaled\n" % n)
