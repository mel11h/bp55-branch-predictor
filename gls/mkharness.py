#!/usr/bin/env python3
"""Derive the gate-level co-simulation harness from sim/cosim.cc (v2) with three small changes.

usage: mkharness.py <sim/cosim.cc> <out cosim.cc>

Everything that drives the design and compares outputs is unchanged. The changes only concern the
post-reset clear check of step 1, which reads state elements by their RTL names:
  1. In a gate netlist a table that was a memory in the RTL (bim, tctr0, ttag0, ras, ...) is a set of
     separate nets named bim[0] .. bim[63] (synthesis netlist) or bim_0_ .. (routed netlist, where
     buses were bit-blasted to tu0_17_ etc.). The check therefore collects every debug item whose
     name is NAME, NAME[...] or NAME_<digits>_... instead of looking up NAME alone.
  2. Those nets are flop outputs that CXXRTL exposes as "outline" debug items, whose values are only
     computed by debug_eval(); the harness calls t.debug_eval() before reading them.
  3. It prints how many state bits the random initialisation wrote (GLSTATE line on stderr), so the
     report can show that every flop of the netlist started from a random value.
The script fails if any of the patched source lines is not found exactly once.
"""
import sys

src, dst = sys.argv[1:3]
s = open(src).read()


def rep(old, new):
    global s
    if s.count(old) != 1:
        sys.exit("mkharness: pattern found %d times: %r" % (s.count(old), old))
    s = s.replace(old, new)


rep('''      for (const char *nm : zero) {
        if (!items.table.count(nm)) { fail("clear-item-missing", 0); fprintf(stderr, "  no debug item %s\\n", nm); continue; }
        for (auto &it : items.table.at(nm)) {''',
    '''      t.debug_eval();  // GL: flop outputs are outline debug items
      auto match = [](const std::string &k, const std::string &nm) {  // GL: NAME, NAME[..], NAME_<digit>..
        if (k.compare(0, nm.size(), nm) != 0) return false;
        if (k.size() == nm.size()) return true;
        char c = k[nm.size()];
        return c == '[' || (c == '_' && k.size() > nm.size() + 1 && isdigit((unsigned char)k[nm.size() + 1]));
      };
      for (const char *nm : zero) {
        std::vector<cxxrtl::debug_item> its;
        for (auto &kv : items.table) if (match(kv.first, nm)) for (auto &it : kv.second) its.push_back(it);
        if (its.empty()) { fail("clear-item-missing", 0); fprintf(stderr, "  no debug item %s\\n", nm); continue; }
        size_t nbits = 0; for (auto &it : its) nbits += it.width * it.depth;
        if (bad == 0 && a == optind) fprintf(stderr, "GLCLEAR %s items=%zu bits=%zu\\n", nm, its.size(), nbits);
        for (auto &it : its) {''')
rep('''    idle_inputs(); t.p_f__pc.set<uint32_t>(rng());
    t.p_rst__n.set<bool>(false);''',
    '''    { size_t nb = 0; for (auto &kv : items.table) for (auto &it : kv.second)  // GL: report randomised state bits
        if (!(it.flags & cxxrtl::debug_item::INPUT) && (it.type == cxxrtl::debug_item::WIRE || it.type == cxxrtl::debug_item::MEMORY)) nb += it.width * it.depth;
      if (a == optind) fprintf(stderr, "GLSTATE randomised_bits=%zu\\n", nb); }
    idle_inputs(); t.p_f__pc.set<uint32_t>(rng());
    t.p_rst__n.set<bool>(false);''')
s = s.replace('#include <cstdio>', '#include <cctype>\n#include <cstdio>', 1)
open(dst, "w").write("// generated by gls/mkharness.py from sim/cosim.cc; do not edit\n" + s)
