#!/usr/bin/env python3
"""Derive a stimulus recorder from sim/cosim.cc (RTL CXXRTL co-simulation, v2 harness).

usage: mkrecorder.py <sim/cosim.cc> <out recorder.cc>

The recorder is the unchanged co-simulation (same stimulus generator, same model checks, same
PASS/FAIL), with two changes:
  1. every clock edge is recorded: just before the rising edge, all BP55 inputs and all outputs
     (after the design has settled) are appended to the file named by $REC_FILE, 24 little-endian
     32-bit words per cycle (layout below; cg/act/replay.cpp reads the same layout);
  2. with $REC_ZERO_INIT=1 the initial state is all-zero instead of random (the random numbers are
     still drawn, so the stimulus stream is the same). A gate netlist simulated from an all-zero
     state then starts from exactly the RTL's state, and recorded outputs can be compared cycle
     by cycle.
Record layout (words):  0 f_pc  1 r_push_addr  2 r_target  3 u_pc  4 u_target  5-7 r_ckpt
  8-11 u_meta  12 control bits (0 f_fire 1 r_fire 2 r_ghr_shift 3 r_taken 4 r_push 5 r_pop
  6 r_thr_shift 7 u_fire 8 u_isbr 9 u_taken 10 rst_n, 16-18 u_type)  13 reserved
  14 f_target  15 f_ras_top  16-19 f_meta  20-22 f_ckpt  23 output bits (0 f_busy 1 f_hit
  2 f_taken 3 f_dir, 4-6 f_type)
"""
import sys

src, dst = sys.argv[1:3]
s = open(src).read()


def rep(old, new):
    global s
    if s.count(old) != 1:
        sys.exit("mkrecorder: pattern found %d times: %r" % (s.count(old), old))
    s = s.replace(old, new)


rep("auto tick = [&]() { t.p_clk.set<bool>(true);",
    "auto tick = [&]() { rec_cycle(t);  t.p_clk.set<bool>(true);")
rep("uint32_t v = rng();", "uint32_t v = rng(); if (rec_zero) v = 0;")
rep("template <size_t N> static uint32_t *wr(cxxrtl::wire<N> &w) { return w.next.data; }", r'''template <size_t N> static uint32_t *wr(cxxrtl::wire<N> &w) { return w.next.data; }
// ---- recorder (cg/act/mkrecorder.py) ----
static FILE *rec_f = nullptr;
static bool rec_zero = false;
static void rec_cycle(Top &t) {
  if (!rec_f) return;
  t.step();
  uint32_t w[24] = {0};
  w[0] = t.p_f__pc.get<uint32_t>(); w[1] = t.p_r__push__addr.get<uint32_t>(); w[2] = t.p_r__target.get<uint32_t>();
  w[3] = t.p_u__pc.get<uint32_t>(); w[4] = t.p_u__target.get<uint32_t>();
  for (int i = 0; i < 3; i++) w[5 + i] = rd(t.p_r__ckpt)[i];
  for (int i = 0; i < 4; i++) w[8 + i] = rd(t.p_u__meta)[i];
  w[12] = (uint32_t)t.p_f__fire.get<bool>() | (uint32_t)t.p_r__fire.get<bool>() << 1 | (uint32_t)t.p_r__ghr__shift.get<bool>() << 2 |
          (uint32_t)t.p_r__taken.get<bool>() << 3 | (uint32_t)t.p_r__push.get<bool>() << 4 | (uint32_t)t.p_r__pop.get<bool>() << 5 |
          (uint32_t)t.p_r__thr__shift.get<bool>() << 6 | (uint32_t)t.p_u__fire.get<bool>() << 7 | (uint32_t)t.p_u__isbr.get<bool>() << 8 |
          (uint32_t)t.p_u__taken.get<bool>() << 9 | (uint32_t)t.p_rst__n.get<bool>() << 10 | t.p_u__type.get<uint32_t>() << 16;
  w[14] = t.p_f__target.get<uint32_t>(); w[15] = t.p_f__ras__top.get<uint32_t>();
  for (int i = 0; i < 4; i++) w[16 + i] = rd(t.p_f__meta)[i];
  for (int i = 0; i < 3; i++) w[20 + i] = rd(t.p_f__ckpt)[i];
  w[23] = (uint32_t)t.p_f__busy.get<bool>() | (uint32_t)t.p_f__hit.get<bool>() << 1 | (uint32_t)t.p_f__taken.get<bool>() << 2 |
          (uint32_t)t.p_f__dir.get<bool>() << 3 | t.p_f__type.get<uint32_t>() << 4;
  fwrite(w, sizeof w, 1, rec_f);
}
// ---- end recorder ----''')
rep("  uint64_t g_bad = 0;\n", '''  uint64_t g_bad = 0;
  if (getenv("REC_FILE")) { rec_f = fopen(getenv("REC_FILE"), "wb"); if (!rec_f) { perror("REC_FILE"); return 2; } }
  rec_zero = getenv("REC_ZERO_INIT") && atoi(getenv("REC_ZERO_INIT"));
''')
rep("  return g_bad != 0;\n}", "  if (rec_f) fclose(rec_f);\n  return g_bad != 0;\n}")
open(dst, "w").write("// generated by cg/act/mkrecorder.py from sim/cosim.cc; do not edit\n" + s)
