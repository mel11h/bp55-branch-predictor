#!/usr/bin/env python3
"""Gate-level copy of verif/tb_bp55_xprop.sv for a (clock-gated) netlist.

usage: mk_tb_xprop_gl.py <verif/tb_bp55_xprop.sv> <netlist.v[.gz]> <out.sv> [--reset-edge]

The stimulus, the order of the checks and every check on the outputs are unchanged. Only the
places where the testbench reads RTL-internal state are rewritten, because a gate netlist has no
arrays:
  * count_x_tables(): instead of dut.bim[i], dut.tctr0[i], ... it tests every netlist net that
    belongs to those tables (NAME[..] in a synthesis netlist, NAME_<n>_.. in an OpenROAD netlist,
    found from the wire declarations); xcnt counts nets that hold an X;
  * dut.bim[0][1:0] in one $display is replaced by the first bimodal net found;
  * {dut.ghr, dut.thr, dut.rasp} is f_ckpt[36:0] (f_ckpt = {ras_top, rasp, thr, ghr}, rtl/bp55.sv).
With --reset-edge, rst_n starts at 1 and falls at 0.1 ns, so that reset is asserted by an edge
(the original starts with rst_n = 0, which an edge-triggered behavioural flop model never sees if
its clock is gated; see xprop_gl.sh).
The script fails if a rewritten pattern is not found exactly once.
"""
import gzip
import re
import sys

tb_path, net_path, out_path = sys.argv[1:4]
reset_edge = "--reset-edge" in sys.argv[4:]
tb = open(tb_path).read()
op = gzip.open if net_path.endswith(".gz") else open
net = op(net_path, "rt").read()

wires = []
for m in re.finditer(r"^\s*(?:wire|reg|output|input)\s*(\[\d+:\d+\])?\s*(\\\S+|\w+)\s*;", net, re.M):
    wires.append(m.group(2))
TABLES = ["bim", "tctr0", "tctr1", "tctr2", "ttag0", "ttag1", "ttag2", "ras", "tu0", "tu1", "tu2"]
groups = {}
for t in TABLES:
    pat = re.compile(r"^\\?" + t + r"(\[|_\d|$)")
    groups[t] = [w for w in wires if pat.match(w)]
    if not groups[t]:
        sys.exit(f"mk_tb_xprop_gl: no nets for table {t}")


def ref(w):
    return "dut." + (w + " " if w.startswith("\\") else w)


def rep(old, new):
    global tb
    if tb.count(old) != 1:
        sys.exit(f"mk_tb_xprop_gl: pattern found {tb.count(old)} times: {old!r}")
    tb = tb.replace(old, new)


m = re.search(r"  task automatic count_x_tables\(\);.*?endtask\n", tb, re.S)
if not m:
    sys.exit("mk_tb_xprop_gl: count_x_tables not found")
body = ["  task automatic count_x_tables();   // gate level: every net of the tables (mk_tb_xprop_gl.py)",
        "    xcnt = 0;"]
for t in TABLES:
    for w in groups[t]:
        body.append(f"    if ($isunknown({ref(w)})) xcnt++;")
body.append("  endtask\n")
tb = tb[:m.start()] + "\n".join(body) + tb[m.end():]
bim0 = sorted(groups["bim"], key=lambda w: [int(x) for x in re.findall(r"\d+", w)])[0]
rep("bim=%b\", f_hit, f_dir, f_taken, f_target, dut.bim[0][1:0]);",
    f"bim(first net)=%b\", f_hit, f_dir, f_taken, f_target, {ref(bim0)});")
rep("dut.ghr, dut.thr, dut.rasp);", "f_ckpt[27:0], f_ckpt[33:28], f_ckpt[36:34]);")
rep("(^{dut.ghr, dut.thr, dut.rasp})", "(^f_ckpt[36:0])")
if reset_edge:
    rep("logic clk=0, rst_n=0, f_fire=0;", "logic clk=0, rst_n=1, f_fire=0;")
    rep("    tick(); rst_n=1;\n", "    #0.1 rst_n=0; tick(); rst_n=1;   // --reset-edge\n")
tb = ("// generated by cg/gls/mk_tb_xprop_gl.py from verif/tb_bp55_xprop.sv; do not edit\n"
      f"// table nets checked: " + ", ".join(f"{t} {len(groups[t])}" for t in TABLES) + "\n" + tb)
open(out_path, "w").write(tb)
print("table nets: " + ", ".join(f"{t} {len(groups[t])}" for t in TABLES))
